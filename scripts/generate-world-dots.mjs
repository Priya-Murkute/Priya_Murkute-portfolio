/**
 * Writes src/data/worldDots.ts, the land mask behind the dotted world map on
 * the About Me page.
 *
 * The world is sampled on a regular grid: a dot wherever the centre of a cell
 * falls on land (Natural Earth, via the world-atlas package). Each row is
 * stored as hex, four columns to a digit, so the whole map is a few KB. The
 * page draws the dots itself; nothing is fetched at runtime.
 *
 * Run after changing STEP, or the extent:  npm run map
 */
import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "src", "data", "worldDots.ts");

// Degrees between neighbouring dots. Finer is crisper when zoomed in, and larger.
const STEP = 1.5;
// The map's latitude extent: Antarctica is left off, it only pushes everything else small.
const NORTH = 84;
const SOUTH = -57;
const WEST = -180;
const EAST = 180;

const cols = Math.round((EAST - WEST) / STEP);
const rows = Math.round((NORTH - SOUTH) / STEP);

const topology = require("world-atlas/land-110m.json");
const land = feature(topology, topology.objects.land);

const hexRows = [];
let dots = 0;
for (let row = 0; row < rows; row += 1) {
  const lat = NORTH - (row + 0.5) * STEP;
  let hex = "";
  for (let col = 0; col < cols; col += 4) {
    let digit = 0;
    for (let bit = 0; bit < 4; bit += 1) {
      const c = col + bit;
      if (c < cols && geoContains(land, [WEST + (c + 0.5) * STEP, lat])) {
        digit |= 8 >> bit;
        dots += 1;
      }
    }
    hex += digit.toString(16);
  }
  hexRows.push(hex);
}

const source = `// Generated by scripts/generate-world-dots.mjs (npm run map). Don't edit by hand.

/** The grid the land dots sit on. Row 0 is the northernmost, column 0 the westernmost. */
export const DOT_GRID = {
  step: ${STEP},
  west: ${WEST},
  east: ${EAST},
  north: ${NORTH},
  south: ${SOUTH},
  cols: ${cols},
  rows: ${rows},
} as const;

/** One string per row, four columns to a hex digit, the leftmost column in the digit's top bit. */
export const DOT_ROWS: readonly string[] = [
${hexRows.map((hex) => `  "${hex}",`).join("\n")}
];
`;

await writeFile(OUTPUT, source);
console.log(`${dots} land dots on a ${cols}×${rows} grid → ${path.relative(ROOT, OUTPUT)}`);
